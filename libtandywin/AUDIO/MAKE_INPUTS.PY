 for i in range(steps):
  vals=([0x88,0x1a,0x94,0xa0,0x21,0xbf,0xc8,0x2b,0xdf,0xe7,0xf8] if i==0 else [0x94+(i%8),0xf8+(i%5)])
  if i==5:vals += [0xe7,0xe7]
  for b in vals:commands+=bytes([0x50,b])
  commands+=b'\x70' if fast else b'\x62'
 commands+=b'\x66';h+=commands;struct.pack_into('<I',h,4,len(h)-4)
 struct.pack_into('<I',h,24,steps*(1 if fast else 735))
