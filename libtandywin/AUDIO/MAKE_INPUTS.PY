def vgm(steps=1200,fast=False,noise=True,loop=False):
 h=bytearray(64);h[:4]=b'Vgm ';struct.pack_into('<I',h,8,0x150);struct.pack_into('<I',h,12,3579545)
 struct.pack_into('<HB',h,40,6,15)
